import { fileURLToPath } from "node:url";
import path from "node:path";
import ejs from "ejs";
import nodemailer from "nodemailer";
import PDFDocument from "pdfkit";

const here = path.dirname(fileURLToPath(import.meta.url));
const receiptTemplate = path.resolve(here, "../templates/payment-receipt.ejs");
const testTemplate = path.resolve(here, "../templates/test-email.ejs");

const LOCALE = process.env.EMAIL_LOCALE || "en-UG";
const TIMEZONE = process.env.EMAIL_TIMEZONE || "Africa/Kampala";

function createTransport(smtp) {
  const secure = smtp.secureMode === "SslOnConnect";
  const requireTLS = smtp.secureMode === "StartTls" || smtp.secureMode === "StartTlsWhenAvailable";
  return nodemailer.createTransport({
    host: smtp.host,
    port: smtp.port,
    secure,
    requireTLS,
    auth: { user: smtp.username, pass: smtp.password },
    tls: { rejectUnauthorized: true },
    connectionTimeout: 15000,
    greetingTimeout: 15000,
    socketTimeout: 30000
  });
}

function money(amount, currency) {
  // Use the ISO currency code in receipts instead of locale-specific symbols
  // (for example, en-UG renders UGX as "USh"). This keeps the ledger currency
  // explicit and consistent across HTML receipts, PDFs and email text.
  const formattedAmount = new Intl.NumberFormat(LOCALE, {
    maximumFractionDigits: currency === "UGX" ? 0 : 2,
    timeZone: TIMEZONE
  }).format(amount);

  return `${formattedAmount} ${currency}`;
}

export function createReceiptPdf(institutionName, receipt) {
  return new Promise((resolve, reject) => {
    const document = new PDFDocument({ size: "A4", margin: 48, info: { Title: `Fee receipt ${receipt.receiptNumber}`, Author: institutionName } });
    const chunks = [];
    document.on("data", chunk => chunks.push(chunk));
    document.on("end", () => resolve(Buffer.concat(chunks)));
    document.on("error", reject);

    const line = (label, value) => {
      document.font("Helvetica-Bold").fontSize(10).fillColor("#334155").text(label, 48, document.y, { continued: true, width: 170 });
      document.font("Helvetica").fillColor("#0f172a").text(value || "—", { width: 325 });
      document.moveDown(0.55);
    };

    document.fillColor("#0f172a").font("Helvetica-Bold").fontSize(17).text(institutionName.toUpperCase(), { align: "center" });
    document.moveDown(0.35);
    document.font("Helvetica").fontSize(11).fillColor("#475569").text("OFFICIAL FEE PAYMENT RECEIPT", { align: "center" });
    document.moveDown(0.8);
    document.moveTo(48, document.y).lineTo(547, document.y).strokeColor("#cbd5e1").stroke();
    document.moveDown(1.1);
    document.font("Helvetica-Bold").fontSize(11).fillColor("#166534").text("PAYMENT VERIFIED AND LOGGED");
    document.moveDown(0.8);
    line("Student", receipt.studentName);
    line("Registration number", receipt.studentNumber);
    line("Receipt number", receipt.receiptNumber);
    line("Transaction reference", receipt.transactionReference);
    line("Payment channel", receipt.channel);
    line("Payment date", new Intl.DateTimeFormat(LOCALE, { dateStyle: "medium", timeStyle: "short", timeZone: TIMEZONE }).format(new Date(receipt.paidAt)));
    document.moveDown(0.8);
    document.font("Helvetica").fontSize(10).fillColor("#475569").text("AMOUNT RECEIVED");
    document.font("Helvetica-Bold").fontSize(20).fillColor("#166534").text(money(receipt.amount, receipt.currency));
    document.moveDown(0.8);
    document.font("Helvetica").fontSize(10).fillColor("#475569").text("REMAINING STUDENT BALANCE");
    document.font("Helvetica-Bold").fontSize(14).fillColor(receipt.balance <= 0 ? "#166534" : "#991b1b").text(money(receipt.balance, receipt.currency));
    document.moveDown(2);
    document.moveTo(48, document.y).lineTo(547, document.y).strokeColor("#cbd5e1").stroke();
    document.moveDown(0.7);
    document.font("Helvetica").fontSize(9).fillColor("#64748b").text("This receipt was generated by the SMIS Finance Engine.", { align: "center" });
    document.end();
  });
}

export async function renderReceiptHtml(payload) {
  return ejs.renderFile(receiptTemplate, {
    institutionName: payload.institutionName,
    institutionEmail: payload.institutionEmail,
    recipient: payload.recipient,
    receipt: payload.receipt,
    amountText: money(payload.receipt.amount, payload.receipt.currency),
    balanceText: money(payload.receipt.balance, payload.receipt.currency),
    paidAtText: new Intl.DateTimeFormat(LOCALE, { dateStyle: "medium", timeStyle: "short", timeZone: TIMEZONE }).format(new Date(payload.receipt.paidAt))
  });
}

export async function sendReceiptEmail(payload) {
  const html = await renderReceiptHtml(payload);
  const pdf = await createReceiptPdf(payload.institutionName, payload.receipt);
  const transport = createTransport(payload.smtp);
  try {
    const result = await transport.sendMail({
      from: { name: payload.sender.name, address: payload.sender.address },
      to: payload.recipient,
      subject: `Official fee receipt: ${payload.receipt.currency} ${payload.receipt.amount.toLocaleString(LOCALE)} [Ref: ${payload.receipt.receiptNumber}]`,
      text: `Dear Student / Parent, payment ${payload.receipt.receiptNumber} of ${money(payload.receipt.amount, payload.receipt.currency)} has been credited to ${payload.institutionName}. Remaining balance: ${money(payload.receipt.balance, payload.receipt.currency)}.`,
      html,
      attachments: [{ filename: `Receipt-${payload.receipt.receiptNumber}.pdf`, content: pdf, contentType: "application/pdf" }]
    });
    return { messageId: result.messageId };
  } finally {
    transport.close();
  }
}

export async function sendTestEmail(payload) {
  const html = await ejs.renderFile(testTemplate, { institutionName: payload.institutionName, senderName: payload.sender.name });
  const transport = createTransport(payload.smtp);
  try {
    const result = await transport.sendMail({
      from: { name: payload.sender.name, address: payload.sender.address },
      to: payload.recipient,
      subject: `${payload.institutionName} — email configuration test`,
      text: `This is a test message from ${payload.institutionName}. Institutional email is configured.`,
      html
    });
    return { messageId: result.messageId };
  } finally {
    transport.close();
  }
}
